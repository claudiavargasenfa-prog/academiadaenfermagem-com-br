# Punção Venosa Periférica — Adulto

> **Material técnico para consulta e treinamento.** A execução deve seguir a prescrição, o POP institucional e as atribuições profissionais vigentes.

## Objetivos

- Obter acesso seguro à rede venosa periférica.
- Administrar medicamentos, soluções, hemocomponentes ou realizar coleta quando indicada.
- Reduzir tentativas, trauma vascular, infecção, infiltração, extravasamento e flebite.

## Materiais necessários

- Cateter venoso periférico no menor calibre compatível com a terapia.
- Garrote limpo e de uso individual conforme protocolo.
- Clorexidina alcoólica 0,5% ou antisséptico definido pela instituição.
- Gaze estéril, luvas de procedimento e bandeja limpa.
- Extensor ou conector valvulado previamente preenchido com SF 0,9%.
- Seringa de 10 ou 20 mL com SF 0,9% para flushing.
- Filme transparente estéril e identificação do acesso.
- Coletor rígido para perfurocortantes.

## Escolha do cateter

| Calibre | Uso clínico mais frequente |
|---|---|
| 24 G | Veias muito frágeis, idosos e terapias de menor velocidade |
| 22 G | Medicamentos e hidratação de rotina |
| 20 G | Maioria dos adultos e terapias intravenosas gerais |
| 18 G | Hemoterapia e reposição volêmica mais rápida, quando a veia comportar |

> ⚠️ Escolha sempre o menor calibre capaz de atender à terapia. Um cateter desproporcional à veia aumenta o risco de flebite mecânica.

## Passo a passo seguro

### 1. Checagem e preparo
Confira a prescrição, identifique o paciente com pelo menos dois identificadores, verifique alergias, explique o procedimento e organize o material em bandeja limpa.

### 2. Higienização das mãos
Higienize as mãos antes de preparar o material e imediatamente antes do contato com o paciente. Calce luvas de procedimento no momento adequado.

### 3. Posicionamento e escolha do membro
Apoie o braço e prefira o membro não dominante. Evite áreas com lesão, infecção, edema, plegia, fístula arteriovenosa ou restrição institucional. Evite áreas de flexão como primeira escolha.

### 4. Garroteamento e escolha da veia
Aplique o garrote aproximadamente 10 a 15 cm acima do local. Prefira veias palpáveis, retilíneas e distais do antebraço, progredindo de distal para proximal.

### 5. Seleção do calibre
Relacione calibre da veia, duração prevista e características da solução. Não escolha automaticamente o maior cateter.

### 6. Antissepsia
Realize a antissepsia e aguarde secagem completa. Não assopre, não abane e não toque novamente no sítio após a preparação da pele.

### 7. Punção
Estabilize a veia, mantenha o bisel voltado para cima e introduza o cateter em ângulo aproximado de 15° a 30°. Siga o limite de tentativas previsto no protocolo institucional.

### 8. Refluxo e progressão
Ao visualizar refluxo sanguíneo, reduza o ângulo, avance discretamente e progrida apenas o cateter. **Nunca reintroduza a agulha no cateter.**

### 9. Conexão segura
Solte o garrote, acione o dispositivo de segurança, descarte imediatamente o perfurocortante e conecte o extensor previamente preenchido.

### 10. Flushing e permeabilidade
Faça flushing com SF 0,9% em seringa de 10 ou 20 mL, observando dor, resistência, edema, palidez ou vazamento. Interrompa se houver qualquer sinal de posicionamento inadequado.

### 11. Fixação e identificação
Cubra com filme transparente estéril, sem ocultar o sítio. Identifique data, hora, calibre e profissional conforme padrão institucional.

### 12. Registro e monitoramento
Registre sítio, calibre, número de tentativas, resposta do paciente e intercorrências. Avalie o acesso antes de cada uso e durante o plantão.

## Não puncionar como primeira escolha

- Membro com fístula arteriovenosa.
- Membro com restrição após cirurgia mamária ou linfadenectomia, conforme avaliação e protocolo.
- Área com infecção, queimadura, edema, hematoma ou lesão de pele.
- Veia endurecida, dolorosa ou com sinais inflamatórios.
- Região de flexão quando houver alternativa mais segura.

## Sinais de alerta no acesso

- Dor, ardor ou sensibilidade.
- Rubor, calor e edema.
- Endurecimento ou cordão venoso palpável.
- Ausência de refluxo associada a resistência.
- Infiltração, extravasamento ou vazamento.
- Secreção, febre ou suspeita de infecção.

# Identificação e Manejo da Flebite

Flebite é a inflamação da veia, podendo apresentar dor, eritema, edema, calor e cordão palpável no trajeto vascular.

## Tipos principais

- **Mecânica:** trauma na inserção, movimentação ou calibre inadequado para a veia.
- **Química:** irritação relacionada ao pH, osmolaridade, concentração ou velocidade do medicamento.
- **Bacteriana:** quebra de técnica asséptica, manipulação inadequada ou curativo comprometido.
- **Pós-infusional:** sinais inflamatórios que surgem após a retirada do cateter.

## Avaliação clínica e conduta

| Situação observada | Conduta de enfermagem |
|---|---|
| Sítio íntegro, sem dor, rubor ou edema | Manter avaliação periódica |
| Dor ou rubor discreto | Reavaliar imediatamente e seguir o protocolo institucional |
| Dor associada a rubor e/ou edema | Suspender a infusão, avaliar retirada, registrar e comunicar conforme protocolo |
| Cordão venoso palpável, endurecimento ou piora dos sinais | Remover o dispositivo, realizar nova punção em outro sítio, registrar e notificar |
| Drenagem purulenta ou suspeita de infecção | Remover, comunicar imediatamente a equipe responsável e seguir investigação e tratamento institucional |

## Bundle de prevenção

1. Higienizar as mãos antes e após toda manipulação.
2. Manter técnica asséptica na inserção e nas conexões.
3. Friccionar conectores com antisséptico pelo tempo definido no protocolo e aguardar secagem.
4. Utilizar o menor calibre compatível com a terapia.
5. Escolher sítio estável e evitar flexões quando possível.
6. Manter curativo limpo, seco, aderido e com o sítio visível.
7. Avaliar dor, rubor, edema, calor e permeabilidade antes de cada uso.
8. Conhecer diluição, compatibilidade, tempo e velocidade de infusão.
9. Retirar prontamente o cateter quando não houver mais indicação clínica ou diante de complicação.

## Registro obrigatório

Documente data e hora, membro e sítio, calibre, tentativas, condição da pele, permeabilidade, sinais encontrados, conduta realizada, comunicação à equipe e resposta do paciente.

